"""The `narrating` step's plug-in point (FR-901, ADR-068).

The orchestrator hands each published pick to a `Narrator` and stores what it returns: the
evidence document (`recommendations.evidence`) and an optional narrative (`narratives`).
S3-T08 supplies the full evidence document and the template or LLM narrative by implementing
this protocol. `MinimalNarrator` is the default until then: a small, deterministic evidence
document built only from engine output, and no narrative text.

The narrator runs after selection and never feeds back into scoring, ranking, or selection.
A narrator that raises falls back to `MinimalNarrator`; a narrative problem never fails a run
(ARCHITECTURE section 4.1).
"""

from __future__ import annotations

import math
from collections.abc import Mapping
from dataclasses import dataclass, field
from datetime import date
from typing import Any, Protocol, runtime_checkable

from supertrends.narrative.evidence import build_evidence
from supertrends.narrative.template import narrate as template_narrate
from supertrends.scoring.config import ScoringConfig
from supertrends.scoring.factor import FactorResult, get_path
from supertrends.selection.ranking import Pick, Selection

__all__ = [
    "DISCLAIMER",
    "MinimalNarrator",
    "NarratedPick",
    "NarrativeText",
    "Narrator",
    "PickContext",
    "TemplateNarrator",
    "minimal_evidence",
]

DISCLAIMER = (
    "Super Trends output is general market analysis generated by an algorithm from technical "
    "and fundamental data. It is not investment advice, not a recommendation tailored to you, "
    "and not an offer to buy or sell any security. The algorithm can be and often is wrong. "
    "Past and backtested performance does not predict future results. You are responsible for "
    "your own decisions."
)
TOP_FACTORS = 3


@dataclass(frozen=True)
class NarrativeText:
    """One stored narrative (`narratives` row). `source` is `llm` or `template`."""

    text: str
    source: str
    prompt_version: str
    model: str | None = None
    tokens_in: int | None = None
    tokens_out: int | None = None
    attempts: int = 1
    rejection_reasons: tuple[str, ...] = ()


@dataclass(frozen=True)
class PickContext:
    """Everything a narrator may read for one pick: engine output only, never LLM output."""

    pick: Pick
    trade_date: date
    snapshot: Mapping[str, Any]
    factor_results: Mapping[str, FactorResult]
    config: ScoringConfig
    selection: Selection | None = None


@dataclass(frozen=True)
class NarratedPick:
    """What the narrator returns: the evidence document and an optional narrative."""

    evidence: Mapping[str, Any]
    narrative: NarrativeText | None = None
    extra: Mapping[str, Any] = field(default_factory=dict)


@runtime_checkable
class Narrator(Protocol):
    """Builds the evidence document and narrative of one pick. Must not mutate its input."""

    def narrate(self, ctx: PickContext) -> NarratedPick: ...


def _clean(value: Any) -> Any:
    if isinstance(value, float) and not math.isfinite(value):
        return None
    return value


def _path(snapshot: Mapping[str, Any], path: str) -> Any:
    try:
        return _clean(get_path(snapshot, path))
    except (KeyError, TypeError):
        return None


def minimal_evidence(ctx: PickContext) -> dict[str, Any]:
    """A deterministic evidence document from the score card, snapshot and factor results.

    The full section 7.17 document arrives with S3-T08; this one carries the fields the run
    summary and tests need, and always the disclaimer.
    """
    pick = ctx.pick
    card = pick.entry.card
    factors = [
        {
            "id": fid,
            "score": card.scores[fid],
            "weight": card.weights[fid],
            "contribution": card.contributions[fid],
            "quality": str(card.qualities[fid]),
        }
        for fid in card.weights
    ]
    sign = 1.0 if pick.side == "buy" else -1.0
    ranked = sorted(card.weights, key=lambda fid: (-sign * card.contributions[fid], fid))
    line = _path(ctx.snapshot, "daily.supertrend.line")
    return {
        "ticker": pick.ticker,
        "side": pick.side,
        "rank": pick.rank,
        "trade_date": ctx.trade_date.isoformat(),
        "display_score": pick.display_score,
        "composite": card.composite,
        "confidence": pick.confidence,
        "band": str(pick.band),
        "days_on_list": pick.days_on_list,
        "regime": card.regime,
        "supertrend": {
            "dir_d": pick.entry.st_dir_d,
            "dir_w": _path(ctx.snapshot, "weekly.supertrend_direction"),
            "bars_since_flip": pick.entry.bars_since_flip,
            "line": line,
        },
        "rc_bias": pick.entry.rc_bias,
        "factors": factors,
        "top_factors": list(ranked[:TOP_FACTORS]),
        "invalidation": {
            "level": line,
            "rule": "daily close beyond the daily Supertrend line",
        },
        "adjustments": list(card.adjustments),
        "disclaimer": DISCLAIMER,
    }


class MinimalNarrator:
    """Default narrator: `minimal_evidence` and no narrative text."""

    def narrate(self, ctx: PickContext) -> NarratedPick:
        return NarratedPick(evidence=minimal_evidence(ctx))


class TemplateNarrator:
    """The S3-T08 narrator (FR-901, ADR-067, ADR-069): the full evidence document and the
    deterministic template narrative.

    The evidence is built from engine output only, to the committed schema (the test suite
    validates it; jsonschema is a dev dependency), and then handed to the template, so the
    narrative reads the stored document and nothing it writes flows back into scoring or
    selection. A failure raises; the orchestrator falls back to `MinimalNarrator` for that pick.
    """

    def narrate(self, ctx: PickContext) -> NarratedPick:
        doc = build_evidence(
            ctx.pick,
            snapshot=ctx.snapshot,
            results=ctx.factor_results,
            config=ctx.config,
            trade_date=ctx.trade_date,
            selection=ctx.selection,
        )
        result = template_narrate(doc)
        return NarratedPick(
            evidence=doc,
            narrative=NarrativeText(
                text=result.text,
                source=result.source,
                prompt_version=result.prompt_version or "template-v1",
                model=result.model,
            ),
        )
