"""Generate THIRD_PARTY_LICENSES.md from the Python environment and ui/package-lock.json.

Exits 1 when any dependency has a license outside the allowlist (MIT, BSD, Apache-2.0,
ISC, PSF, MPL-2.0, LGPL). GPL, AGPL, SSPL, and unknown licenses always fail: strong
copyleft cannot be combined with a noncommercial license. REVIEWED_DEV_EXCEPTIONS lists
permissive licenses outside the allowlist that are accepted only for dev-only npm tools
that never ship in the image or the UI bundle.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from dataclasses import dataclass
from pathlib import Path

ALLOWED = re.compile(
    r"^(MIT|(0)?BSD|Apache|ISC|PSF|Python Software Foundation|MPL|Mozilla Public License|"
    r"LGPL|GNU Lesser General Public License|Zlib|CC0)",
    re.IGNORECASE,
)
# Strong copyleft, never allowed. LGPL is matched by ALLOWED first.
DENIED = re.compile(r"(AGPL|SSPL|(?<!L)GPL|GNU General Public|GNU Affero|UNKNOWN)", re.IGNORECASE)

REVIEWED_DEV_EXCEPTIONS = {
    # package name -> license; build and lint tooling only, never bundled.
    "caniuse-lite": "CC-BY-4.0",
    "minimatch": "BlueOak-1.0.0",
    "lru-cache": "BlueOak-1.0.0",
    "@isaacs/nonrecursive-glob-match": "BlueOak-1.0.0",
}

OWN_PACKAGES = {"supertrends"}


@dataclass(frozen=True)
class Dep:
    ecosystem: str
    name: str
    version: str
    license: str
    runtime: bool


def _is_allowed_term(term: str) -> bool:
    term = term.strip().strip("()").strip()
    return bool(ALLOWED.match(term)) and not DENIED.search(term)


def is_allowed(license_text: str) -> bool:
    """True when the license (an SPDX expression or classifier list) is on the allowlist.

    "A OR B" and "A; B" (dual licensing) pass when any option passes; "A AND B" needs all.
    """
    text = license_text.strip()
    if not text:
        return False
    options = re.split(r"\s+OR\s+|;", text.strip("()"))
    for option in options:
        terms = re.split(r"\s+AND\s+", option.strip().strip("()"))
        if all(_is_allowed_term(t) for t in terms):
            return True
    return False


def _normalize(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def python_deps(env_json: Path, runtime_txt: Path) -> list[Dep]:
    runtime = {
        _normalize(line.split("==")[0].split("[")[0].strip())
        for line in runtime_txt.read_text().splitlines()
        if line.strip() and not line.lstrip().startswith(("#", "-", "."))
    }
    deps = []
    for row in json.loads(env_json.read_text()):
        name = row["Name"]
        if _normalize(name) in OWN_PACKAGES:
            continue
        deps.append(
            Dep("python", name, row["Version"], row["License"], _normalize(name) in runtime)
        )
    return deps


def npm_deps(lock: Path) -> list[Dep]:
    deps = []
    for key, meta in json.loads(lock.read_text()).get("packages", {}).items():
        if not key:
            continue
        name = key.rsplit("node_modules/", 1)[-1]
        deps.append(
            Dep(
                "npm",
                name,
                str(meta.get("version", "")),
                str(meta.get("license") or "UNKNOWN"),
                not meta.get("dev", False),
            )
        )
    return deps


def violations(deps: list[Dep]) -> list[Dep]:
    bad = []
    for dep in deps:
        if is_allowed(dep.license):
            continue
        reviewed = REVIEWED_DEV_EXCEPTIONS.get(dep.name) == dep.license
        if dep.ecosystem == "npm" and reviewed and not dep.runtime:
            continue
        bad.append(dep)
    return bad


def render(deps: list[Dep]) -> str:
    lines = [
        "# Third-Party Licenses",
        "",
        "Generated by `scripts/gen-third-party-licenses.sh` from `uv.lock` (installed environment)",
        "and `ui/package-lock.json`. Do not edit by hand. `runtime` dependencies ship in the image",
        "or the UI bundle; `dev` dependencies are build, test, and lint tools only.",
        "",
    ]
    for ecosystem, title in (("python", "Python"), ("npm", "npm (ui/)")):
        rows = sorted(
            {d for d in deps if d.ecosystem == ecosystem},
            key=lambda d: (d.name.lower(), d.version),
        )
        lines += [f"## {title}", "", "| Package | Version | License | Scope |", "|---|---|---|---|"]
        lines += [
            f"| {d.name} | {d.version} | {d.license} | {'runtime' if d.runtime else 'dev'} |"
            for d in rows
        ]
        lines.append("")
    return "\n".join(lines)


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--python-json", type=Path, required=True)
    parser.add_argument("--python-runtime", type=Path, required=True)
    parser.add_argument("--npm-lock", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args(argv)

    deps = python_deps(args.python_json, args.python_runtime) + npm_deps(args.npm_lock)
    args.output.write_text(render(deps))
    bad = violations(deps)
    for dep in bad:
        print(f"x license not allowed: {dep.ecosystem} {dep.name} {dep.version}: {dep.license}")  # noqa: T201
    if bad:
        return 1
    print(f"ok {len(deps)} dependencies, all licenses allowed; wrote {args.output}")  # noqa: T201
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
